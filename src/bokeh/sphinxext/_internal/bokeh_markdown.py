""" Support the Markdown version of the documentation.

The documentation build writes a Markdown file next to every HTML page, and an
``llms.txt`` index of those files, so that AI coding agents and other tools can
read the documentation without parsing HTML. The Markdown is generated by the
``sphinx_llm.txt`` extension, which runs a second Sphinx build with a Markdown
builder.

This extension registers Markdown output for standard docutils and Sphinx
nodes that the Markdown builder does not know. Without these handlers, the
Markdown build emits an "unknown node type" warning for each of them, which
fails the documentation build.

It also provides helpers for Bokeh's own directives and roles to supply a
Markdown alternative next to content that only makes sense in HTML.

"""

# -----------------------------------------------------------------------------
# Boilerplate
# -----------------------------------------------------------------------------
from __future__ import annotations

import logging  # isort:skip

log = logging.getLogger(__name__)

# -----------------------------------------------------------------------------
# Imports
# -----------------------------------------------------------------------------

import posixpath
from typing import Any

from docutils import nodes
from sphinx import addnodes

from . import PARALLEL_SAFE, SphinxParallelSpec

# -----------------------------------------------------------------------------
# Globals and constants
# -----------------------------------------------------------------------------

__all__ = (
    "MARKDOWN_FORMAT",
    "is_markdown_build",
    "markdown_block",
    "markdown_inline",
    "markdown_pass",
    "markdown_skip",
    "setup",
)

#: The ``format`` of every Markdown builder. Sphinx looks up node handlers by
#: builder name first, and by builder format second.
MARKDOWN_FORMAT = "markdown"

# -----------------------------------------------------------------------------
# General API
# -----------------------------------------------------------------------------

# -----------------------------------------------------------------------------
# Dev API
# -----------------------------------------------------------------------------


def is_markdown_build(app: Any) -> bool:
    """Return whether the running Sphinx build writes Markdown."""
    return getattr(app.builder, "format", None) == MARKDOWN_FORMAT


def markdown_block(text: str) -> nodes.raw:
    """Return a node that renders ``text`` as a Markdown block.

    The node is ignored by every builder except Markdown builders.

    """
    return nodes.raw("", f"\n\n{text.strip()}\n\n", format=MARKDOWN_FORMAT)


def markdown_inline(text: str) -> nodes.raw:
    """Return a node that renders ``text`` as inline Markdown.

    The node is ignored by every builder except Markdown builders.

    """
    return nodes.raw("", text, format=MARKDOWN_FORMAT)


def markdown_pass(translator: Any, node: nodes.Node) -> None:
    """Render only the children of a node."""


def markdown_skip(translator: Any, node: nodes.Node) -> None:
    """Leave a node and its children out of the Markdown output."""
    raise nodes.SkipNode


def setup(app: Any) -> SphinxParallelSpec:
    """ Required Sphinx extension setup function. """
    # Standard nodes are already registered with docutils, so override=True
    # only silences the "already registered" warning. HTML output is unchanged.
    for node, handlers in _STANDARD_NODE_HANDLERS.items():
        app.add_node(node, override=True, **{MARKDOWN_FORMAT: handlers})

    return PARALLEL_SAFE

# -----------------------------------------------------------------------------
# Private API
# -----------------------------------------------------------------------------


def _visit_raw(translator: Any, node: nodes.raw) -> None:
    # Raw HTML, LaTeX, etc. is meaningless in Markdown. Only pass through
    # content that was written for Markdown.
    if MARKDOWN_FORMAT in node.get("format", "").split():
        if isinstance(node.parent, nodes.TextElement):
            translator.add(node.astext())
        else:
            # a block, for example from a ``.. raw:: markdown`` directive
            translator.ensure_eol(2)
            translator.add(node.astext().strip())
            translator.ensure_eol(2)
    raise nodes.SkipNode


def _visit_image(translator: Any, node: nodes.image) -> None:
    # The Markdown pages are published next to the HTML pages, so link to the
    # image files of the HTML build, relative to the current page.
    uri = node["uri"]
    builder = translator.builder
    image = builder.env.images.get(uri)
    if image is not None:
        docdir = posixpath.dirname(builder.current_doc_name)
        uri = posixpath.relpath(posixpath.join("_images", image[1]), docdir or ".")
    translator.add(f"![{node.get('alt', 'image')}]({uri})")
    raise nodes.SkipNode


def _visit_block(translator: Any, node: nodes.Node) -> None:
    translator.ensure_eol(2)


def _depart_block(translator: Any, node: nodes.Node) -> None:
    translator.ensure_eol(2)


_STANDARD_NODE_HANDLERS: dict[type[nodes.Element], tuple[Any, Any]] = {
    # the content of HTML <meta> tags
    nodes.meta: (markdown_skip, None),
    # reStructuredText comments are notes for documentation authors
    nodes.comment: (markdown_skip, None),
    nodes.raw: (_visit_raw, None),
    nodes.image: (_visit_image, None),
    # the explanation of an abbreviation is an HTML tooltip, keep the text
    nodes.abbreviation: (markdown_pass, markdown_pass),
    # captions of figures and code blocks
    nodes.caption: (_visit_block, _depart_block),
    # horizontal lists are bullet lists split into columns
    addnodes.hlist: (markdown_pass, markdown_pass),
    addnodes.hlistcol: (markdown_pass, markdown_pass),
}

