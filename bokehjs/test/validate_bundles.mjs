// Exercise actual distributed bundles and Python serialization without a
// development-server transform or a browser-test framework rewriting imports.
// The installed-wheel CI step supplies the fixture and browser explicitly.
import assert from "node:assert/strict"
import {readFile} from "node:fs/promises"
import {createServer} from "node:http"
import {extname, resolve, sep} from "node:path"
import {fileURLToPath} from "node:url"

import {chromium} from "playwright-core"

const root = resolve(fileURLToPath(new URL("..", import.meta.url)))
const executable = process.argv.find((arg) => arg.startsWith("--executable="))?.slice("--executable=".length)
const fixture_path = process.argv.find((arg) => arg.startsWith("--fixture="))?.slice("--fixture=".length)
assert.ok(fixture_path, "--fixture must name JSON generated by test/support/serialization_fixture.py")
const fixture = JSON.parse(await readFile(fixture_path, "utf8"))
const server = createServer(async (request, response) => {
  try {
    const pathname = new URL(request.url, "http://localhost").pathname
    if (pathname == "/") {
      response.setHeader("Content-Type", "text/html; charset=utf-8")
      response.end('<!doctype html><html><head><meta charset="utf-8"></head><body></body></html>')
      return
    }
    const path = resolve(root, `.${decodeURIComponent(pathname)}`)
    if (!path.startsWith(`${root}${sep}`)) {
      response.writeHead(403).end()
      return
    }
    const data = await readFile(path)
    response.setHeader("Content-Type", extname(path) == ".mjs" || extname(path) == ".js" ? "text/javascript; charset=utf-8" : "application/octet-stream")
    response.end(data)
  } catch {
    response.writeHead(404).end()
  }
})
await new Promise((resolve, reject) => {
  server.once("error", reject)
  server.listen(0, "127.0.0.1", resolve)
})
let browser
try {
  const {port} = server.address()
  browser = await chromium.launch({
    headless: true,
    executablePath: executable ?? process.env.BOKEH_CHROME,
    args: ["--enable-unsafe-swiftshader"],
  })
  for (const kind of ["classic", "legacy ESM", "native ESM"]) {
    for (const suffix of [".js", ".min.js"]) {
      const page = await browser.newPage()
      const errors = []
      page.on("pageerror", (error) => errors.push(String(error)))
      try {
        await page.goto(`http://127.0.0.1:${port}/`)
        if (kind == "classic") {
          for (const name of ["bokeh", "bokeh-gl", "bokeh-api", "bokeh-widgets", "bokeh-tables", "bokeh-mathjax"]) {
            await page.addScriptTag({url: `/build/js/${name}${suffix}`})
          }
        }
        await page.evaluate(async ({kind, suffix, fixture}) => {
          let runtime
          if (kind == "classic") {
            runtime = window.Bokeh
          } else if (kind == "native ESM") {
            runtime = await import(`/build/esm/bokeh${suffix}`)
          } else {
            runtime = (await import(`/build/js/bokeh.esm${suffix}`)).default
            for (const name of ["gl", "api", "widgets", "tables", "mathjax"]) {
              await import(`/build/js/bokeh-${name}.esm${suffix}`)
            }
          }
          const {check_serialization_contract} = await import("/test/support/serialization_contract.mjs")
          check_serialization_contract(runtime, fixture)
          // Preserve the existing module-callback protocol across all formats.
          const callback = runtime.Models.get("CustomJS").create({
            module: true,
            code: "export default (_args, _obj, {value}) => value + 2",
          })
          if (await callback.execute(callback, {value: 40}) !== 42) {
            throw new Error("Module callback returned an incorrect value")
          }
        }, {kind, suffix, fixture})
        assert.deepEqual(errors, [], `${kind}${suffix} browser errors`)
        console.log(`passed bundle serialization: ${kind}${suffix}`)
      } finally {
        await page.close()
      }
    }
  }
} finally {
  await browser?.close()
  await new Promise((resolve, reject) => server.close((error) => error == null ? resolve() : reject(error)))
}
